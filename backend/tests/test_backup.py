import sqlite3
from pathlib import Path

import pytest

from scripts.backup import create_backup, restore_backup


def test_sqlite_backup_and_restore_roundtrip(tmp_path: Path):
    database = tmp_path / "app.db"
    storage = tmp_path / "storage"
    storage.mkdir()
    (storage / "note.txt").write_text("kaynak", encoding="utf-8")
    with sqlite3.connect(database) as con:
        con.execute("create table items (id integer primary key, name text)")
        con.execute("insert into items (name) values ('ilk')")

    archive = tmp_path / "backup"
    manifest = create_backup(
        output=archive,
        database_url=f"sqlite:///{database}",
        storage_dir=storage,
    )
    assert manifest["storage_files"] == 1

    with sqlite3.connect(database) as con:
        con.execute("insert into items (name) values ('sonra')")
    (storage / "note.txt").unlink()

    restore_backup(
        archive=archive,
        database_url=f"sqlite:///{database}",
        storage_dir=storage,
        force=True,
    )
    with sqlite3.connect(database) as con:
        names = [row[0] for row in con.execute("select name from items order by id")]
    assert names == ["ilk"]
    assert (storage / "note.txt").read_text(encoding="utf-8") == "kaynak"


@pytest.mark.skipif(
    pytest.importorskip("embedded_postgres", reason="embedded-postgres kurulu değil") is None,
    reason="embedded-postgres kurulu değil",
)
def test_postgres_backup_and_restore_roundtrip(tmp_path: Path):
    from embedded_postgres import PostgresServer
    from embedded_postgres.postgres_server import POSTGRES_BIN_PATH
    import psycopg

    server = PostgresServer(tmp_path / "pgdata", cleanup_mode="delete")
    try:
        server.psql("CREATE DATABASE medspaced;")
        url = server.get_uri("medspaced")
        with psycopg.connect(url) as con:
            con.execute("create table items (id integer primary key generated by default as identity, name text)")
            con.execute("insert into items (name) values ('ilk')")
            con.commit()

        archive = tmp_path / "backup"
        create_backup(
            output=archive,
            database_url=url,
            storage_dir=tmp_path / "storage",
            pg_bin=POSTGRES_BIN_PATH,
        )
        with psycopg.connect(url) as con:
            con.execute("drop table items")
            con.commit()

        restore_backup(
            archive=archive,
            database_url=url,
            storage_dir=tmp_path / "storage",
            pg_bin=POSTGRES_BIN_PATH,
            force=True,
        )
        with psycopg.connect(url) as con:
            assert con.execute("select name from items").fetchone()[0] == "ilk"
    finally:
        server.cleanup()


def test_prune_backups_keeps_newest(tmp_path):
    import os
    from scripts.backup import MANIFEST, prune_backups

    root = tmp_path / "backups"
    root.mkdir()
    for index in range(3):
        backup = root / f"2026010{index + 1}-000000"
        backup.mkdir()
        (backup / MANIFEST).write_text("{}", encoding="utf-8")
        os.utime(backup / MANIFEST, (index + 1, index + 1))

    removed = prune_backups(directory=root, keep=2, dry_run=True)
    assert [path.name for path in removed] == ["20260101-000000"]
    assert (root / "20260101-000000").exists()

    removed = prune_backups(directory=root, keep=2)
    assert [path.name for path in removed] == ["20260101-000000"]
    assert not (root / "20260101-000000").exists()
    assert (root / "20260102-000000").exists()
    assert (root / "20260103-000000").exists()
